# 60/40 of a 18% and a 6% volatility asset: portfolio volatility as a function of the correlation.
rho = np.linspace(-1, 1, 201)
sig = np.sqrt(0.36 * 0.0324 + 0.16 * 0.0036 + 2 * 0.24 * rho * 0.18 * 0.06)
ax.plot(rho, sig * 100, color=ACCENT, lw=2, label='portfolio volatility')
ax.axhline(13.2, color=BAD, ls='--', lw=1.2, label='averaging the volatilities: 13.2%')
ax.scatter([-0.2], [10.58], color=GOOD, s=50, zorder=3)
ax.annotate('rho = -0.2: 10.58%', xy=(-0.2, 10.58), xytext=(-0.05, 9.2), color=GOOD, arrowprops=dict(arrowstyle='->', color=GOOD))
ax.scatter([-1, 1], [8.40, 13.2], color=INK, s=24, zorder=3)
ax.text(-0.95, 8.05, '8.40% at rho = -1', fontsize=9)
ax.set_xlabel('correlation between the two assets')
ax.set_ylabel('portfolio volatility (% per year)')
ax.set_ylim(7.5, 14.2)
ax.legend(fontsize=8, loc='upper left')
ax.set_title('The same weights, different correlation: the risk is not an average', loc='left')
