t = np.linspace(0, 10, 300)
mu, sig = 0.10, 0.20
mean = 100 * np.exp(mu * t)
med = 100 * np.exp((mu - sig**2 / 2) * t)
lo = 100 * np.exp((mu - sig**2 / 2) * t - 0.6745 * sig * np.sqrt(t))
hi = 100 * np.exp((mu - sig**2 / 2) * t + 0.6745 * sig * np.sqrt(t))
ax.fill_between(t, lo, hi, color=ACCENT, alpha=.10, label='25%-75% band')
ax.plot(t, mean, color=GOOD, lw=2, label='mean: 271.83 at 10 years')
ax.plot(t, med, color=WARM, lw=2, label='median: 222.55 at 10 years')
ax.set_xlabel('Horizon (years)')
ax.set_ylabel('Price (USD, start 100)')
ax.set_title('SPY at 10% drift, 20% volatility', loc='left')
ax.legend(loc='upper left', fontsize=8)
