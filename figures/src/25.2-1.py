k=np.linspace(2.5,6.0,200)
pn=stats.norm.cdf(-k)
p3=stats.norm.cdf(-3.0)
pw=p3*(k/3.0)**-4.0
ax.semilogy(k,1/pn/251,color=BAD,lw=2.2,label='Normal tail')
ax.semilogy(k,1/pw/251,color=ACCENT,lw=2.2,label='power law, tail index 4')
ax.axvline(4.1667,color=MUTED,ls=':',lw=1.2)
ax.plot([3.0],[1/p3/251],'o',color=INK,ms=6)
ax.annotate('both forced to agree here\n(3 sigma, once in 3.0 years)',xy=(3.0,1/p3/251),
            xytext=(3.15,0.35),fontsize=7,color=INK,arrowprops=dict(arrowstyle='->',color=INK,lw=.8))
ax.plot([4.1667],[1/stats.norm.cdf(-4.1667)/251],'o',color=BAD,ms=6)
ax.plot([4.1667],[1/(p3*(4.1667/3)**-4)/251],'o',color=ACCENT,ms=6)
ax.annotate('258 years',xy=(4.1667,258),xytext=(12,0),textcoords='offset points',fontsize=8,color=BAD)
ax.annotate('11.0 years',xy=(4.1667,10.98),xytext=(12,-4),textcoords='offset points',fontsize=8,color=ACCENT)
ax.annotate('a -5% day\nwhen sigma = 1.2%',xy=(4.1667,1.2),xytext=(4.35,0.8),fontsize=7,color=MUTED)
ax.set_xlabel('size of the down day (multiples of sigma)')
ax.set_ylabel('years you would wait for one')
ax.set_title('Move 1.17 sigma further out and the two models disagree 23-fold',loc='left')
ax.legend(fontsize=7,loc='upper left')
